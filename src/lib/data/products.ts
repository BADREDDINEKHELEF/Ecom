export const getProductsByNiche = (nicheId: string) =>
  products.filter((p) => p.nicheId === nicheId)

export const getFeaturedProducts = (nicheId?: string) =>
  products.filter((p) => p.isFeatured && (!nicheId || p.nicheId === nicheId))

export const getProductById = (id: string) =>
  products.find((p) => p.id === id)

export const getRelatedProducts = (product: Product, limit = 4) =>
  products
    .filter((p) => p.nicheId === product.nicheId && p.id !== product.id)
    .slice(0, limit)
